_COMPILED_LEXICON_CACHE = None


def get_full_compiled_lexicon():
    global _COMPILED_LEXICON_CACHE
    if _COMPILED_LEXICON_CACHE is not None:
        return _COMPILED_LEXICON_CACHE

    full_lex = dict(BASE_ARAMAIC_DICTIONARY)

    for root_heb, root_meaning, dialect_str, forms in ARAMAIC_VERB_ROOTS:
        if root_heb not in full_lex:
            full_lex[root_heb] = {
                'he': f"{root_meaning} (שורש: {root_heb})",
                'dialect': dialect_str,
                'cat': 'פועל',
                'note': f"שורש פועל ארמי ({dialect_str})"
            }
        for form_w, form_he in forms:
            if form_w not in full_lex:
                full_lex[form_w] = {
                    'he': form_he,
                    'dialect': dialect_str,
                    'cat': 'פועל',
                    'note': f"שורש: {root_heb} ({root_meaning})"
                }
            for pref_c, pref_h in [('ד', 'ש'), ('ו', 'ו'), ('כד ', 'כאשר '), ('לא ', 'לא ')]:
                comb_w = f"{pref_c}{form_w}"
                if comb_w not in full_lex and not form_w.startswith('ד'):
                    full_lex[comb_w] = {
                        'he': f"{pref_h}{form_he}",
                        'dialect': dialect_str,
                        'cat': 'פועל',
                        'note': f"תחילית \"{pref_c}\" + {form_w} (שורש: {root_heb})"
                    }

    noun_suffixes = [
        ('א', 'ה{m} (יידוע בארמית)'),
        ('יה', '{m} שלו'),
        ('ך', '{m} שלך'),
        ('נא', '{m} שלנו'),
        ('הון', '{m} שלהם (בבלי/זוהר)'),
        ('יהון', '{m} שלהם (ירושלמי/זוהר)'),
        ('ין', '{m} (ריבוי בארמית)')
    ]
    noun_prefixes = [
        ('ד', 'של ה{m} / שה{m}'),
        ('ב', 'ב{m}'),
        ('ל', 'ל{m}'),
        ('מ', 'מן ה{m}')
    ]

    for stem, heb_m, dialect_str, cat_str in ARAMAIC_NOUN_STEMS:
        clean_m = heb_m.split('/')[0].strip()
        for suf, suf_tpl in noun_suffixes:
            w_suf = f"{stem}{suf}"
            if w_suf not in full_lex:
                full_lex[w_suf] = {
                    'he': suf_tpl.format(m=clean_m),
                    'dialect': dialect_str,
                    'cat': cat_str,
                    'note': f"נטייה של \"{stem}א\" ({heb_m})"
                }
        base_noun = f"{stem}א"
        for pref, pref_tpl in noun_prefixes:
            w_pref = f"{pref}{base_noun}"
            if w_pref not in full_lex:
                full_lex[w_pref] = {
                    'he': pref_tpl.format(m=clean_m),
                    'dialect': dialect_str,
                    'cat': cat_str,
                    'note': f"תחילית \"{pref}-\" + {base_noun} ({heb_m})"
                }

    for dict_path in [
        os.path.join(settings.BASE_DIR, 'tts_dictionary.json'),
        os.path.join(settings.BASE_DIR, 'articles', 'tts_dictionary.json')
    ]:
        if os.path.exists(dict_path):
            try:
                with open(dict_path, 'r', encoding='utf-8') as f:
                    tts_d = json.load(f)
                    for k, v in tts_d.items():
                        k_clean = k.strip()
                        v_clean = re.sub(r'[\u0591-\u05C7]', '', str(v)).strip()
                        if k_clean and k_clean not in full_lex and v_clean != k_clean:
                            full_lex[k_clean] = {
                                'he': str(v).strip(),
                                'dialect': 'בבלי, ירושלמי',
                                'cat': 'ראשי תיבות ומונחים',
                                'note': f'מונח וראשי תיבות בספרות הש"ס והפוסקים'
                            }
            except Exception:
                pass

    learned_path = os.path.join(settings.BASE_DIR, 'aramaic_learned_cache.json')
    if os.path.exists(learned_path):
        try:
            with open(learned_path, 'r', encoding='utf-8') as f:
                learned_d = json.load(f)
                for lk, lv in learned_d.items():
                    q_term = lv.get('query') or lk.split('|')[-1]
                    if q_term and q_term not in full_lex and lv.get('main_translation'):
                        full_lex[q_term] = {
                            'he': lv['main_translation'],
                            'dialect': 'בבלי, ירושלמי, זוהר',
                            'cat': 'מונח תלמודי',
                            'note': lv.get('grammar_breakdown', '')
                        }
        except Exception:
            pass

    _COMPILED_LEXICON_CACHE = full_lex
    return full_lex


def aramaic_translator_view(request):
    full_lex = get_full_compiled_lexicon()

    def heb_sort_key(item):
        clean_term = re.sub(r'[^א-ת]', '', item['term'])
        return clean_term or item['term']

    bavli_list = []
    yerushalmi_list = []
    zohar_list = []

    for k, v in full_lex.items():
        first_l = re.sub(r'[^א-ת]', '', k)[:1]
        if not first_l:
            continue
        item_obj = {'term': k, 'first_letter': first_l, **v}
        if 'בבלי' in v['dialect']:
            bavli_list.append(item_obj)
        if 'ירושלמי' in v['dialect']:
            yerushalmi_list.append(item_obj)
        if 'זוהר' in v['dialect']:
            zohar_list.append(item_obj)

    bavli_list.sort(key=heb_sort_key)
    yerushalmi_list.sort(key=heb_sort_key)
    zohar_list.sort(key=heb_sort_key)

    return {
        'current_page': 'aramaic_translator',
        'bavli_json': json.dumps(bavli_list, ensure_ascii=False),
        'yerushalmi_json': json.dumps(yerushalmi_list, ensure_ascii=False),
        'zohar_json': json.dumps(zohar_list, ensure_ascii=False),
        'bavli_count': len(bavli_list),
        'yerushalmi_count': len(yerushalmi_list),
        'zohar_count': len(zohar_list),
        'total_count': len(full_lex)
    }


def _extract_senses_recursively(senses_list):
    defs = []
    if not isinstance(senses_list, list):
        return defs
    for s in senses_list:
        if isinstance(s, dict):
            d = strip_tags(s.get('definition', '')).strip()
            if d:
                defs.append(d)
            sub_senses = s.get('senses', [])
            if sub_senses:
                defs.extend(_extract_senses_recursively(sub_senses))
    return defs


def _query_sefaria_lexicon(word_to_query, full_lex, depth=0):
    if depth > 1 or not word_to_query:
        return None
    try:
        sef_url = f"https://www.sefaria.org/api/words/{urllib.parse.quote(word_to_query)}"
        req = urllib.request.Request(sef_url, headers={'User-Agent': 'Mozilla/5.0'})
        with urllib.request.urlopen(req, timeout=4) as resp:
            sef_data = json.loads(resp.read().decode('utf-8'))
            if not isinstance(sef_data, list) or not sef_data:
                return None

            collected_defs = []
            lex_names = []
            redirect_roots = []

            for entry in sef_data:
                lex_name = entry.get('parent_lexicon', '')
                content = entry.get('content', {})
                entry_defs = _extract_senses_recursively(content.get('senses', []))
                for ed in entry_defs:
                    clean_ed = re.sub(r'\s+', ' ', ed).strip()
                    ref_match = re.search(r'^(?:see|v\.|cmp\.|=)\s*([א-ת\u0591-\u05C7]+)', clean_ed, flags=re.IGNORECASE)
                    if ref_match and len(clean_ed) < 35:
                        ref_heb = re.sub(r'[^א-ת]', '', ref_match.group(1))
                        if ref_heb and ref_heb != word_to_query:
                            redirect_roots.append(ref_heb)
                    elif len(clean_ed) > 2:
                        collected_defs.append(clean_ed)
                        if lex_name and lex_name not in lex_names:
                            lex_names.append(lex_name)

            if not collected_defs and redirect_roots:
                target_root = redirect_roots[0]
                if target_root in full_lex:
                    e = full_lex[target_root]
                    return {
                        'detected_direction': 'ארמית ⬅ עברית (נטייה משורש)',
                        'main_translation': e['he'],
                        'dialects_list': [d.strip() for d in e['dialect'].split(',')],
                        'grammar_breakdown': f"הטיה מן השורש הארמי \"{target_root}\" ({e['cat']})",
                        'usage_example': e['note']
                    }
                return _query_sefaria_lexicon(target_root, full_lex, depth=depth + 1)

            if collected_defs:
                raw_eng = " ; ".join(collected_defs[:3])
                clean_eng = re.sub(r'\b(ch\.|pl\.|m\.|f\.|q\.?\s*v\.?|cmp\.|Targ\.|Y\.|Bab\.|preced\.|art\.)\b', '', raw_eng, flags=re.IGNORECASE)
                he_trans = clean_eng
                try:
                    gt_url = f"https://translate.googleapis.com/translate_a/single?client=gtx&sl=en&tl=iw&dt=t&q={urllib.parse.quote(clean_eng[:320])}"
                    gt_req = urllib.request.Request(gt_url, headers={'User-Agent': 'Mozilla/5.0'})
                    with urllib.request.urlopen(gt_req, timeout=3) as gt_resp:
                        gt_json = json.loads(gt_resp.read().decode('utf-8'))
                        he_trans = "".join([part[0] for part in gt_json[0] if part[0]]).strip()
                except Exception:
                    pass

                lex_label = ", ".join(lex_names[:2]) or "מילון הערוך וגסטרוב"
                return {
                    'detected_direction': 'ארמית ⬅ עברית',
                    'main_translation': he_trans,
                    'dialects_list': ['בבלי', 'ירושלמי', 'זוהר'],
                    'grammar_breakdown': f"מקור לקסיקלי: {lex_label} ({raw_eng[:120]})",
                    'usage_example': f"התיבה \"{word_to_query}\" מתבארת במילוני הארמית במשמעות: {he_trans}"
                }
    except Exception:
        pass
    return None


def _lookup_term_smart(clean_q, full_lex):
    if clean_q in full_lex:
        e = full_lex[clean_q]
        return {
            'detected_direction': 'ארמית ⬅ עברית',
            'main_translation': e['he'],
            'dialects_list': [d.strip() for d in e['dialect'].split(',')],
            'grammar_breakdown': f"{e['cat']} | מופיע ב: {e['dialect']}",
            'usage_example': e['note']
        }

    heb_matches = []
    for k, v in full_lex.items():
        he_words = [w.strip() for w in re.split(r'[/,()—\-!?]', v['he']) if w.strip()]
        if clean_q in he_words or any(clean_q == hw for hw in he_words):
            heb_matches.append((k, v))

    if heb_matches:
        heb_matches.sort(key=lambda x: len(x[0]))
        top_matches = [f"{k} ({v['dialect']})" for k, v in heb_matches[:5]]
        return {
            'detected_direction': 'עברית ⬅ ארמית',
            'main_translation': "  •  ".join(top_matches),
            'dialects_list': ['בבלי', 'ירושלמי', 'זוהר'],
            'grammar_breakdown': f"מקבילות בארמית עבור המילה העברית \"{clean_q}\"",
            'usage_example': heb_matches[0][1].get('note', '')
        }

    prefixes = [
        ('דקא', 'שעומד ו... (ד + קא)'),
        ('בגין', 'בשביל / מפני'),
        ('קא', 'הווה מתמשך (עומד ו...)'),
        ('ד', 'ש... / של (תחילית זיקה בארמית)'),
        ('ב', 'ב... (תחילית יחס)'),
        ('ל', 'ל... / אל (תחילית יחס)'),
        ('מ', 'מן / מתוך (תחילית)'),
        ('ו', 'ו... (ו\' החיבור)'),
        ('כ', 'כמו / כפי')
    ]
    for pref, pref_meaning in prefixes:
        if clean_q.startswith(pref) and len(clean_q) - len(pref) >= 2:
            stem = clean_q[len(pref):]
            if stem in full_lex:
                e = full_lex[stem]
                return {
                    'detected_direction': 'ארמית ⬅ עברית (פירוק דקדוקי)',
                    'main_translation': f"{pref_meaning.split('(')[0].strip()} + {e['he']}",
                    'dialects_list': [d.strip() for d in e['dialect'].split(',')],
                    'grammar_breakdown': f"תחילית \"{pref}-\" ({pref_meaning}) + המילה \"{stem}\" ({e['he']})",
                    'usage_example': e['note']
                }

    sef_res = _query_sefaria_lexicon(clean_q, full_lex)
    if sef_res:
        return sef_res

    return None


def execute_aramaic_translation(request):
    q = request.GET.get('q', '').strip()
    direction = request.GET.get('dir', 'auto').strip()
    dialect = request.GET.get('dialect', 'bavli').strip()

    if not q:
        return {'error': 'נא להזין מילה, ביטוי או משפט לתרגום.'}, 400

    clean_q = re.sub(r'[^\w\sא-ת"״\'׳\-]', '', q).strip()
    cache_key = f"aramaic_trans_v10_{direction}_{dialect}_{clean_q}"
    cached_res = cache.get(cache_key)
    if cached_res:
        return cached_res, 200

    full_lex = get_full_compiled_lexicon()
    WORD_TOKEN_RE = re.compile(r'[א-ת\u0591-\u05bd\u05bf\u05c1\u05c2\u05c4\u05c5\u05c7]+')
    NON_HEB_RE = re.compile(r'[^א-ת]+')

    def find_talmud_examples(search_term, target_dialect):
        heb_words = [w for w in re.findall(r'[א-ת]+', search_term) if len(w) >= 2]
        if not heb_words:
            return []
        target_w = heb_words[0]
        examples = []

        if target_dialect == 'zohar':
            for z_item in ZOHAR_AUTHENTIC_CORPUS:
                raw_t = z_item['text']
                toks = list(WORD_TOKEN_RE.finditer(raw_t))
                spans = [t.span() for t in toks if target_w in NON_HEB_RE.sub('', t.group(0))]
                if spans:
                    s0, e0 = spans[0]
                    marked = (
                        raw_t[:s0] +
                        f'<mark style="background-color: #fde047; color: #000; padding: 0 4px; border-radius: 4px; font-weight: bold;">{raw_t[s0:e0]}</mark>' +
                        raw_t[e0:]
                    )
                    examples.append({
                        'book': z_item['book'],
                        'chapter': z_item['chapter'],
                        'verse': z_item['verse'],
                        'ref': f"{z_item['book']} ({z_item['chapter']})",
                        'dialect_tag': 'ספר הזוהר',
                        'text': format_divine_name(marked),
                        'full_text': format_divine_name(marked)
                    })
            if not examples:
                entry_note = full_lex.get(clean_q, {}).get('note', f'התיבה "{clean_q}" בלשון ספר הזוהר הקדוש')
                examples.append({
                    'book': 'ספר הזוהר הקדוש',
                    'chapter': 'לשון הזוהר',
                    'verse': '1',
                    'ref': 'ספר הזוהר הקדוש (מאגר לשון הזוהר)',
                    'dialect_tag': 'ספר הזוהר',
                    'text': format_divine_name(f'בספר הזוהר: <mark style="background-color: #fde047; color: #000; padding: 0 4px; border-radius: 4px; font-weight: bold;">{clean_q}</mark> — {entry_note}'),
                    'full_text': format_divine_name(f'מקור מלשון ספר הזוהר הקדוש עבור "{clean_q}":\n\n{entry_note}')
                })
            return examples[:3]

        if target_dialect == 'yerushalmi':
            qs = TorahText.objects.filter(book__startswith='ירושלמי ')
        else:
            qs = TorahText.objects.filter(chapter__startswith='דף').exclude(book__startswith='ירושלמי ')

        for hw in heb_words[:2]:
            qs = qs.filter(clean_text__icontains=hw)

        rows = list(qs.values('book', 'chapter', 'verse', 'text_with_nikkud', 'clean_text')[:25])
        for r in rows:
            raw_t = r.get('text_with_nikkud') or r.get('clean_text') or ''
            toks = list(WORD_TOKEN_RE.finditer(raw_t))
            spans = [t.span() for t in toks if target_w in NON_HEB_RE.sub('', t.group(0))]
            if spans:
                s0, e0 = spans[0]
                win_s = max(0, s0 - 90)
                win_e = min(len(raw_t), e0 + 90)
                snippet = (
                    ("... " if win_s > 0 else "") +
                    raw_t[win_s:s0] +
                    f'<mark style="background-color: #fde047; color: #000; padding: 0 4px; border-radius: 4px; font-weight: bold;">{raw_t[s0:e0]}</mark>' +
                    raw_t[e0:win_e] +
                    (" ..." if win_e < len(raw_t) else "")
                )
                examples.append({
                    'book': r['book'],
                    'chapter': r['chapter'],
                    'verse': r['verse'],
                    'ref': f"{r['book']} ({r['chapter']}, {r['verse']})",
                    'dialect_tag': 'ירושלמי' if r['book'].startswith('ירושלמי ') else 'בבלי',
                    'text': format_divine_name(snippet),
                    'full_text': ''
                })
                if len(examples) >= 3:
                    break
        return examples

    talmud_examples = find_talmud_examples(clean_q, dialect)
    resolved_data = _lookup_term_smart(clean_q, full_lex)

    if not resolved_data:
        words_in_phrase = [w for w in clean_q.split() if len(w) >= 2]
        if len(words_in_phrase) > 1:
            word_translations = []
            for w in words_in_phrase:
                sub_res = _lookup_term_smart(w, full_lex)
                if sub_res:
                    word_translations.append(f"{w} = {sub_res['main_translation']}")
            if word_translations:
                resolved_data = {
                    'detected_direction': 'ארמית ⇄ עברית (פירוק ביטוי)',
                    'main_translation': " | ".join(word_translations),
                    'dialects_list': ['בבלי', 'ירושלמי', 'זוהר'],
                    'grammar_breakdown': 'פירוק מילות הביטוי מתוך המילון התלמודי',
                    'usage_example': talmud_examples[0]['text'] if talmud_examples else ''
                }

    if not resolved_data:
        acr_hit = Acronym.objects.filter(Q(short=clean_q) | Q(short__icontains=clean_q)).first()
        if acr_hit:
            resolved_data = {
                'detected_direction': 'ראשי תיבות ומונחים ⬅ עברית',
                'main_translation': acr_hit.meaning,
                'dialects_list': ['בבלי', 'ירושלמי'],
                'grammar_breakdown': 'נמצא במילון ראשי התיבות והמונחים של הספרייה',
                'usage_example': f"{acr_hit.short}: {acr_hit.meaning}"
            }

    if not resolved_data:
        resolved_data = {
            'detected_direction': 'ארמית ⇄ עברית',
            'main_translation': f'ראה הקשר הסוגיה עבור "{clean_q}" בדוגמאות להלן',
            'dialects_list': ['בבלי', 'ירושלמי', 'זוהר'],
            'grammar_breakdown': 'תיבה מתוך מאגרי הש"ס והזוהר',
            'usage_example': talmud_examples[0]['text'] if talmud_examples else ''
        }

    result_payload = {
        'query': clean_q,
        'selected_dialect': dialect,
        'detected_direction': resolved_data.get('detected_direction', 'ארמית ⇄ עברית'),
        'main_translation': format_divine_name(resolved_data.get('main_translation', '')),
        'dialects_list': resolved_data.get('dialects_list', ['בבלי', 'ירושלמי', 'זוהר']),
        'grammar_breakdown': format_divine_name(resolved_data.get('grammar_breakdown', '')),
        'usage_example': format_divine_name(resolved_data.get('usage_example', '')),
        'talmud_examples': talmud_examples
    }

    cache.set(cache_key, result_payload, 3600 * 24)
    return result_payload, 200